			<p class="text-header">
				dimensionalismo<br>
				arte avanzata interdisciplinare
			</p>

			<p class="text-content">
				La ricerca interdisciplinare, volta ad approfondire la conoscenza, è uno degli eventi più significativi dei nostri giorni. Quando in essa convergono arte e scienza i rapporti che ne intercorrono sono particolarmente importanti. <br>
				Da anni Pierelli lavora su questo tema, collaborando con alcuni tra i più validi ricercatori scientifici. <br>
				Ne sono testimonianza sue opere quali: <br>
				<a href="cuspide">Piastra Inox</a> (o superficie a cuspide) del 1965. La cui struttura verte sulla singolarità, si ritroverà poco dopo il '65 tra i modelli geometrici della teoria delle catastrofi di Renè Thom; <br>
				<a href="ipercubo">Ipercubo</a> dello spazio quadrimensionale, realizzato nel 1974 in collaborazione con Giuseppe Arcidiacono ed esposto alla galleria dell'Obelisco in occasione della mostra De Mathematica; <br>
				<a href="nodi">Nodi</a>, sculture topologiche, superfici estremali, sono stati realizzati in collaborazione con Franco Ghione ed esposti alla triennale di Milano nel 1986; <br>
				<a href="test">T.E.S.T.</a>(Trascinamento di Eventi Spazio-Temporali), del 1985/86, esposta alla 42° Biennale di Venezia, sul tema "Arte e Scienza" destinata alla galleria d'arte moderna di Roma; in questo caso l'artista ha rielaborato la forma della scultura ispirandosi ai buchi neri (black holes) teorizzati e scoperti dall'astrofisico Remo Ruffini negli Stati Uniti, rappresentati secondo un modello ottenuto al computer insieme ai suoi collaboratori all'università di Roma. <br>
				Ed altre opere ancora.
			</p>

			<p class="text-content" style="text-align: center">
				Partendo dall'esperienza del suo lavoro Pierelli si è fatto promotore di un nuovo movimento artistico il
			</p>

			<p class="text-header">
				dimensionalismo
			</p>

			<table class="year-table">

				<tr>
					<th class="ie">1</th>
					<th> il <b>DIMENSIONALISMO</b> mira  a riannodare i fili di un comune discorso di conoscenza, iniziato nelle cattedrali gotiche ed esploso in Italia nel '400;</th>
				</tr>

				<tr>
					<th class="ie">2</th>
					<th> il <b>DIMENSIONALISMO</b> è un movimento intellettuale artistico che intende superare la barriera delle tre dimensioni dello spazio; a tale scopo, si propone di avviare una revisione dei principi e della metodologia dell'arte;</th>
				</tr>

				<tr>
					<th class="ie">3</th>
					<th> l'artista del nuovo corso è principalmente un <i>Uomo di pensiero</i> che indaga gli spazi con dimensioni maggiori alla terza. Nelle sue realizzazioni egli opera, come ogni artista, tramite l'intuizione, ma si vale anche di strumenti matematici e della scienza in generale;</th>
				</tr>

				<tr>
					<th class="ie">4</th>
					<th>finché l'uomo è stato ancorato all'esplorazione dello spazio tridimensionale come unica ed esclusiva realtà esistente, non ha avuto alcuna necessità di definire, o ri-definire, il termine <i>dimensione</i>;</th>
				</tr>

				<tr>
					<th class="ie">5</th>
					<th>il pensiero <b>DIMENSIONALISTA</b>, scoprendo e percorrendo mentalmente gli iperspazi, e approfondendo le proprietà topologiche delle figure geometriche, ha inevitabilmente ampliato il concetto di <i>dimensione</i>, conferendogli una valenza superiore, fino a farlo diventare un fenomeno nuovo, differente da quello identificato col termine <i>tridimensionale</i>: nel senso che ogni iperspazio ha proprie caratteristiche specifiche, diverse sia da quello precedente che da quello successivo;</th>
				</tr>

				<tr>
					<th class="ie">6</th>
					<th>la <i>conoscenza</i>, o visione del mondo ( spesso impropriamente sintetizzata o confusa con la parola scienza) come chiave evolutiva dell'umanità, è alla base del programma <b>DIMENSIONALISTA</b> e vi svolge un ruolo propulsivo insostituibile;</th>
				</tr>

				<tr>
					<th class="ie">7</th>
					<th>nell'Umanesimo e nel Rinascimento la <i>conoscenza</i> si sviluppò in gran parte attraverso l'arte. Le prime importanti scoperte sia scientifiche che estetiche, vennero compiute dagli artisti; corona questo periodo Leonardo, che tracciò indelebilmente la via che nel futuro gli artisti "avrebbero dovuto" seguire per fondere sapientemente, e consapevolmente, l'analisi conoscitivo-scientifica con l'emozionalità e l'intuizione artistica.</th>
				</tr>
			</table>

