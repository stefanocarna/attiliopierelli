					<p class="text-content rx-prev">
						Le sculture sonore di Pierelli sono oggetti parlanti, strumenti sensibili al tatto che generano vibrazioni ed armonie arcane se solo le si sfiora o le si percuote, immettendo il fattore tempo in una lettura che utilizza le ipotesi scientifiche e la bellezza estetica delle formule matematiche per tradurle nel poetico linguaggio dell’arte. 
						Dilatandosi nello spazio tramite il suono, tali opere divengono vere e proprie installazioni, combattendo l’apparente staticità della loro austera forma grazie all’animazione acustica, elemento completante-complementare di uno spazio divenuto fluido, “attraversabile”.
