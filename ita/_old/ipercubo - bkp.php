			<p class="text-chapter">
				arte e scienza a confronto
			</p>

			<p class="text-content">
				Diversamente da ciò che accade nel diagramma di Schlegel di un ipercubo<span class="text-tip"></span><a class="tip" 
				title="Nel 1965 fu possibile osservare un ipercubo muoversi all’interno di uno spazio tridimensionale, tramite l’animazione al calcolatore effettuata da Michael Noll (1939). Nel 1977 i due matematici Thomas Banchoff e Charles Strauss realizzarono Hypercube, alla Brown University di Providence, il primo film a colori e in animazione computerizzata, in cui fu possibile vedere l’ipercubo ruotare nello spazio a tre dimensioni."
				style="color: white;"><sup>2</sup></a>, in cui il cubo interno centrale della figura viene semplicemente disegnato, nella scultura di Pierelli esso viene reso addirittura visibile, grazie ai rispecchiamenti. Una sequenza aritmetica regola la struttura IPERSPAZIALE dell’Ipercubo, composto da otto cubi tridimensionali, a loro volta formati da sei superfici quadrate bidimensionali. Nella proiezione prospettica di Schlegel le sei superfici bidimensionali non possono diventare sei cubi, poiché imprigionate in un disegno la cui terza dimensione è solo apparente. Pierelli con la sua opera “ipercubica” è invece riuscito ad andare oltre questo limite. Nella scultura infatti, se il cubo interno si trova alla fine di un altro cubo, distorto dalla prospettiva, e se i lati del primo hanno la stessa misura dei lati che vediamo nel secondo, allora il cubo interno sarà grande esattamente quanto quello esterno. Immaginando poi che il cubo interno cominci ad avanzare, questo crescerà al punto di combaciare perfettamente con quello esterno, ottenendo infine, grazie al gioco creato dalla prospettiva, un nuovo cubo interno, concepito dalla convergenza prospettica effettuata dal “primo” cubo interno.
			</p>

			<p class="text-content">
				Come il Rinascimento seppe raffigurare la terza dimensione su una superficie bidimensionale (artisti come Brunelleschi o Piero della Francesca seppero trasformare in immagini e oggetti le potenzialità della geometria euclidea), offrendo quindi la percezione fisica di idee astratte, allo stesso modo Pierelli è stato capace di rappresentare la quarta dimensione nella tridimensionalità. L’artista marchigiano si servì semplicemente della prospettiva centrale bidimensionale e della sua teoria delle linee convergenti, intese come rette parallele che si incontrano all’infinito, per descrivere qualcosa che l’uomo è ancora soltanto in grado di immaginare.
			</p>

			<p class="text-content">
				L’esempio della scultura di Pierelli dimostra come spesso l’arte divenga il ponte fra conoscenza ed esperienza sensibile, e come quest’ultima sia fortemente influenzata dai processi artistici. Poiché comprensione e visione non possono venir separate, l’arte dona all’osservatore la capacità di "riflessione", fondendone la doppia accezione che deriva dal termine latino REFLECTERE, pensare e specchiare, dunque ragionare e riflettere tramite immagini. L’artista pensa e riflette, attraverso le immagini, tutti quei processi prodotti dall’intelletto umano, rendendo visibile ciò che, altrimenti, rimarrebbe pura astrazione.
			</p>

			<p class="text-content">
					Attraverso la scultura di Pierelli è dunque possibile sostenere la concezione cartesiana<span class="text-tip"></span><a class="tip" 
					title="Cartesio ritiene che il criterio basilare della verità sia l'evidenza: ciò che, mediante l’intuito, appaia indiscutibilmente certo. Poiché la realtà tangibile può essere ingannevole, in quanto soggetta alla percezione sensibile (dubbio metodico), e al contempo anche la matematica e la geometria (discipline che esulano dal mondo sensibile) si rivelano fasulle, nel momento in cui si ammette la possibilità che un'entità superiore (colui che Cartesio soprannomina genio maligno) faccia apparire come reale ciò che non lo è (dubbio iperbolico), l'unica certezza che resta all'uomo è che dubitando l'uomo sia almeno sicuro di esistere (Cogito ergo sum: penso dunque sono)."
					style="color: white;"><sup>3</sup></a> secondo la quale la percezione umana sia ingannevole poiché ci permette, complice il pensiero matematico, di vedere corpi che in realtà non esistono. Ciò che si trova al di là della nostra esperienza può essere percepito soltanto attraverso espedienti di natura illusionistica, ma l’opera d’arte ci porta a riconoscere come tali illusioni ottiche possano comunque creare un mondo davanti a noi.
			</p>

			<p class="text-content">
				«Il punto di partenza per una nuova concezione è dovuto probabilmente a Kandinsky, che nel suo libro <i>Ueber das Geistige in der Kunst</i><span class="text-tip"></span><a class="tip" 
				title="Cfr. W. Kandinsky, Lo spirituale nell’arte, Milano, Editore SE, 2005."
				style="color: white;"><sup>4</sup></a> pone nel 1912 le premesse di un'arte nella quale l'immaginazione dell'artista sarebbe stata sostituita dalla concezione matematica. […]
			</p>

			<p class="text-content">
				Si sostiene che l’arte non ha niente a che fare con la matematica, che quest’ultima costituisce una materia arida, non artistica, un campo puramente intellettuale e di conseguenza estraneo all’arte. Nessuna di queste due argomentazioni è accettabile perché l’arte ha bisogno del sentimento e del pensiero. Il pensiero permette di ordinare i valori emozionali perché da essi possa uscire l’opera d’arte»<span class="text-tip"></span><a class="tip" 
				title="M. Bill, The Mathematical Way of Thinking in the Visual Art of Our Time, in M. Emmer (a cura di), The Visual Mind: art and mathematics, Cambridge, MIT Press, 1993. Citato in M. Emmer (a cura di), Matematica e cultura 2000, Milano, Springer-Verlag, 2000, pp. 149-150."
				style="color: white;"><sup>5</sup></a>.
			</p>

			<p class="text-content">
				L’arte può incontrare la realtà nell’apparenza, poiché tutto quello che la nostra natura rifiuta e che la scienza non è in grado di farci vedere, ci viene offerto da essa. Così, se nell’incertezza delle percezioni sensibili noi andremo a considerare il pensiero matematico, come l’astrazione che rende pensabile la natura, l’opera di un artista sarà allora la sua materializzazione.
			</p>


