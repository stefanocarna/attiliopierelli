			<p class="text-header">
				ipercubo
			</p>

			<p class="text-content">
				Esposta per la prima volta nel giugno del 1974 alla mostra <i>De Mathematica</i>, curata da Filiberto Menna, presso Galleria L’Obelisco di Roma, la scultura <i>Ipercubo</i> venne realizzata in collaborazione con uno dei più geniali scienziati italiani del secondo dopoguerra, Giuseppe Arcidiacono, docente di meccanica superiore all'Università di Perugia e membro dell'Istituto Nazionale di Alta Matematica di Roma. In una delle sue ultime interviste, Pierelli raccontava così la nascita di questo singolare e magico sodalizio: 
			</p>

			<div id="iperspace-machine" class="text-img big c"> 
				<img src="../assets/_hypercube/img/A1.jpg">
				<div class="overbox landscape">
					<div class="tagline overtext">
						Lo scultore Attilio Pierelli con la sua opera <i>Ipercubo</i>
					</div>
				</div>
			</div>

			<p class="text-content">
				«Vidi su un banchetto di libri usati “Tempo, Spazio e Universo” di un autore di origine siciliana, Giuseppe Arcidiacono, […] lo cercai sull’elenco telefonico. Lo trovai, gli chiesi umilmente un colloquio. Mi invitò nella sua casa e ci andai, […]. Gli dissi, sto facendo queste esperienze sulle forme e non ne capisco fino in fondo il significato. Mi fece una lezione che quando uscii, barcollavo. Vide le mie opere e mi disse: lei sta lavorando sulla geometria euclidea, la geometria curva, il preludio all’Iperspazio. […] Con lui mi feci una cultura. […] Mi procurai dei libri e cominciai a studiare. Tutti i giorni, per 10 anni, per almeno tre ore, sul legame tra la realtà e la sua immagine»<span class="text-tip"></span><a class="tip" 
				title="La quarta dimensione di Attilio Pierelli, in «EcoMarcheNews», 11 febbraio 2016, www.ecomarchenews.com/la-quarta-dimensione-di-attilio-pierelli (29 marzo 2017)."
				style="color: white;"><sup>1</sup></a>.
			</p>

			<p class="text-content">
				E proprio verso questi due paradigmi della visione (ciò che si vede e ciò che è realmente) che, a partire da opere come l’<i>Ipercubo</i>, lo scultore marchigiano concentrerà la propria attenzione.  Interamente in acciaio inox e dotato della straordinaria proprietà di autocostruirsi, l’ipercubo di Pierelli è composto da un cubo esterno che l’osservatore, ingannato dall’accorciamento prospettico, vede costituito da sei cubi, le cui facce sono tronchi di piramide rovesciata, all’interno dei quali scorgiamo, per effetto dei rispecchiamenti, un settimo cubo interno.
			</p>

			<p class="text-content">
				Ed ecco come la composizione di ben otto cubi tridimensionali permetterà di vedere un unico IPER-cubo appartenente alla quarta dimensione dell'IPER-spazio. All’interno di questo perfetto binomio di regolarità e simmetria, il motore dell’illusione ottica ottenuta è però la luce: sospeso nello spazio infinito, il corpo geometrico viene attraversato da raggi luminosi che, colpendone l'interno, deformano sul piano la sua immagine. Emanando luce come un cristallo, l’opera penetra così quello spazio misterioso ed impercettibile, la cui risultante sarà una forma complessa e compressa nella sua “dimensionalità”. 
			</p>

			<p class="text-content">
				L’Ipercubo è la prima figura iperspaziale concretizzata da Pierelli, ma in seguito verranno realizzate anche le rappresentazioni di quelli che sono convenzionalmente il primo ed il terzo solido regolare dello spazio a quattro dimensioni, <i>Pentacella</i> e <i>Sedicicella</i>.
			</p>

			<p class="text-content">
				É come se un'esplosione dilaniasse la massa compatta di queste forme quasi magiche che una volta sezionate, composte e ricomposte, mostrano un INTERNO la cui intrinseca irrequietezza lo spinge a volersi fare ESTERNO, con il “dentro” che sembra quasi aspirare a diventare “fuori”. 
			</p>

			<p class="text-content">
				Pierelli vuole liberarsi della forma assoluta (tridimensionale), la distrugge per poi moltiplicarla attraverso nuove coordinate, scoprendo il senso cosmico di una visione di mondi (im)possibili. Ovviamente, queste sculture non sono dei veri oggetti iperspaziali, a noi inaccessibili, ma le loro rappresentazioni nel nostro spazio tridimensionale. Sono fotografie, ombre a tre dimensioni, appunti di un utopico viaggio svolto nel tetraspazio.
			</p>

			<p class="text-content">
				Attraverso le coordinate matematiche degli iperspazi, Pierelli è riuscito a creare delle forme capaci di materializzarsi in corpi geometrici se investite da un sottile velo di luce, a riprova di quel sottile ma profondo legame tra la realtà e la sua immagine, che ci apparirà sempre deformata per via della luce. Un esemplare dell’Ipercubo di Pierelli è stato posto all’ingresso del Campus Scientifico-Sogene dell’Università degli studi di Roma Tor Vergata, una sorta di richiamo visivo sotto forma di “epifania geometrica” per tutti gli studenti che si recano nelle varie sedi delle Facoltà scientifiche.
			</p>


