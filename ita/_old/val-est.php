			<p class="text-content">
				La tendenza, sempre più forte, verso la dimensione plastico-spaziale inizia ad andare di pari passo con una tendenza alla sintesi. Le opere cominciano a venir eseguite tramite l’impiego dei macchinari dell’industria oppure vengono destinate ad essere seriate come un prodotto industriale qualunque. Il repertorio artistico che viene creandosi va così a comporsi di elementi naturalistici artificiali, a metà strada fra civiltà dell’immagine e civiltà della tecnologia; improvvisa nuovi paesaggi e inedite dimensioni, costruendo quasi una
				<span class="text-tip">
					<span style="color: firebrick;">«</span>seconda natura<span style="color: firebrick;">»</span>.</span><a class="tip" 
					title="I. Tomassoni, Arte dopo il 1945, Bologna, Cappelli Editore, 1971, p. 78. 
					style="color: white;"><sup>2</sup></a>
				Come avrebbe detto Lewis Mumford (1895 - 1982) nel suo monumentale scritto<span class="text-tip">
					La città nella storia</span><a class="tip" 
					title="Cfr. R. Assunto, La città di Anfione e la città di Prometeo, Milano, Jaca Book, 1984, p.72."
					style="color: white;"><sup>3</sup></a>
				, si cerca così di conciliare Prometeo (l’uomo della scienza e della tecnica) con Orfeo (colui che attraverso l’arte addomestica la natura). All’interno di questa nuova realtà l’arte però non viene vista come un tentativo di salvare il mondo dal fare alienante della tecnologia industriale o come un suggerimento di rivisitazione della stessa, bensì come una celebrazione della sua autosufficienza: il suo messaggio resta inalterato nel tempo nonostante il perpetuo cambiamento di forma, linguaggio, consistenza e, appunto, immagine.
				Facendo convivere la dimensione delle idee con quella del pensiero, comincia a farsi strada nell’artista del tempo una nuova adesione alla ragione, e da un procedere per convinzioni si passa ad un procedere per tentativi. Non si tratta più di riproporre modelli canonici, né di imporre programmi o progetti indubitabili, ma di affermare una ragione nuova, diversa, che prosegue proprio perché continua a immaginare. E proprio immaginando azzarda - intuisce! - supera e dichiara l’instabilità del precostituito, facendo coesistere la determinazione con l’indeterminazione generata dalla complessità che ci circonda, ma che non per questo sceglie la trasversalità degli stili. Le dimensioni create dall’incertezza vengono affrontate con la disponibilità a modificare anche le proprie convinzioni senza che questo vada a significar il non aver alcuna sicurezza.
				Si sceglie ora di proseguire lungo una determinata strada in maniera razionale, ma con la consapevolezza di non basarsi su verità certe. Si punta a moltiplicare la possibilità del vedere e del percepire, partendo dal presupposto che 
				<span class="text-tip">
					<span style="color: firebrick;">«</span>guardare un’opera d’arte implichi sempre l’attivazione di un processo di apprendimento per tentativi che è al tempo stesso un processo di accumulazione del sapere, nonché la capacità di rispondere ai cambiamenti dell’ambiente modificando la propria personalità e aumentandone la complessità<span style="color: firebrick;">»</span>.</span><a class="tip" 
					title="S. Lux, Incantesimi. Scene d’arte e poesia a Bomarzo, Viterbo, Museo Laboratorio delle Arti Contemporanee dell’Università degli Studi della Tuscia, 1995, p. 24."
					style="color: white;"><sup>4</sup></a>
			</p>

			<p class="text-content">
				Ragione e azzardo divennero dunque le direttrici determinanti del lavoro di una precisa area dell’esperienza artistica di quel periodo a cavallo tra gli anni Sessanta e Settanta del Novecento, periodo in cui l’opera d’arte non chiedeva più un’attenzione fondata su regole, ma una percezione rivelatrice di sé stessa, nel dominio della propria sensibilità. Tra gli artisti italiani che percorreranno questa direzione ci sarà - anche e soprattutto - Attilio Pierelli, che farà parte di quella linea più avanzata, rappresentativa ed innovatrice della scultura italiana del secondo Novecento.
			</p>

