				, ovvero  l'emozione che si prova nel vedere un qualcosa d'istinto, senza logica alcuna. <br>
				Egli si servì delle sue creazioni per giungere alla conoscenza di nuove dimensioni e per incitare l’osservatore a fare lo stesso, rendendo l’immaginazione parte integrante della logica e mettendo in contatto diretto tutte le infinte e possibili relazioni che intercorrono tra lo sguardo e lo spazio. Riuscendo ad unire le conoscenze scientifiche alla sensibilità artistica, Pierelli dimostrò di possedere un ingegno pari a quello dei più grandi maestri dell'Umanesimo.
			</p>

