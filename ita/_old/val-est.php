			<p class="text-chapter">
				premessa storica
			</p>

			<p class="text-content">
				All'inizio della seconda metà del Novecento, nel panorama artistico internazionale cominciano a vedersi i chiari sintomi di un profondo cambiamento. I protagonisti, i movimenti e gli elementi finora cardini iniziano ad apparire come i vecchi strumenti di un presente diventato ormai passato, e sembrano addirittura ostacolare quella pressante esigenza d’immersione totale dell’arte nella vita che si stava demarcando sempre più in quegli anni. <br>
				Senza gerarchie restrittive, l’arte comincia così ad estendere a qualsiasi materiale la possibilità di creare forme, distaccandosi dalla tradizionale idea che tecnica e materiali impiegati forniscano di per sé un giudizio a priori circa il valore di un’opera e tendendo invece a penetrare attivamente nello spazio dell’osservatore avvalendosi di strumenti fino ad allora estranei al linguaggio artistico più tradizionale. Tale propensione, che raggiungerà una diffusione a livello internazionale negli anni Sessanta, porterà gli artisti a servirsi di ogni innovazione tecnico-materica del loro tempo e ad inserirla legittimamente nei processi lavorativi delle proprie espressioni poetiche, creando così "oggetti" difficilmente classificabili all’interno dei generi artistici convenzionali. In questa innovativa direzione, rivoluzionaria è stata soprattutto l’evoluzione della scultura e della concretizzazione del suo legame con la contemporaneità. <br>
				In Italia, a partire dagli anni Sessanta, le poetiche parallele alla scultura si svilupparono secondo traiettorie discontinue, divenendo il più delle volte episodi isolati e di difficile ricostruzione evolutiva. Eppure, fu proprio grazie a questa conclamata non univocità che tali poetiche cominciarono a divenire fonte d’ispirazione e d’incoraggiamento per le nuove generazioni. L'incremento di voci e di esperienze così alternative e diversificate porterà a sua volta alla ri-scoperta dello Spazio nella totalità di tutte le sue accezioni possibili ed attraverso l’utilizzo di ogni tipologia di mezzi e “strumenti” donati dalla modernità. 
			</p>

