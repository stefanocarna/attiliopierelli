			<p class="text-content">
				L’intento di Pierelli fu quello di provare ad avvicinare l’umanità alla conoscenza totale di questo mondo, che rimane essenzialmente ancora puro fenomeno, apparenza inconoscibile nella propria verità. Ed essendo la mente umana, per lo scultore,  il vero “maestro” dell’uomo,  unico capace di  trascendere le tre dimensioni, ogni volta che concepiva un’opera, si ripresentava il problema di come renderla comprensibile non soltanto da chi avesse una preparazione artistica e scientifica, ma, per quanto la cosa potesse risultare ardua e complessa, da chiunque fosse interessato anche solo ad osservarla, attraverso quello che egli chiamava
				<span class="text-tip">
				<span style="color: firebrick;">«</span>plesso solare<span style="color: firebrick;">»</span></span><a class="tip" 
