			<p class="text-content">
				L’arte di Attilio Pierelli fu, per certi versi, un’arte antirazionale: fatta di visioni improvvise e di pure illuminazioni, ma che trovò nei simboli e nelle teorie scientifici il suo massimo grado di espressione. La ricerca condotta per il raggiungimento di tali obiettivi fu lunga e multidisciplinare, ma pur sempre ispirata dalla fondamentale “costante” della sua primitiva intuizione. La sua opera è stata la prova evidente che il rapporto tra arte e scienza non è soltanto possibile ma, soprattutto, necessario per continuare a tendere verso la conoscenza delle molteplici “dimensioni” dell’esistenza. 
			</p>

			



			<p class="text-chapter">
				una poetica tra arte e scienza
			</p>

			<p class="text-content">
				Pierelli fu un vero fuoriclasse dell’arte scultorea internazionale e le sue opere lo dimostrano in maniera tangibile: immagini regolari ma contemporaneamente soggette ad una persistente trasformazione, sculture auto-musicali che variano il loro suono in base all’ambiente, alla prospettiva dalla quale vengono osservate e all’angolazione della luce che le colpisce; sono tutti oggetti che raccontano - ciascuno in maniera diversa - quella che fu l’originale intuizione del loro creatore. L’artista riuscì ad accostare, paragonare ed infine combinare il rigore scientifico con la capacità dell’immaginazione, offrendone poi la sintesi completa all’osservatore. Egli trovò nella scultura lo strumento di indagine ideale per la sperimentazione, in forma concreta, delle innovazioni generate dalla fisica moderna e riuscì quindi ad ottenere risultati plastici inediti sia nella visualizzazione della quarta dimensione geometrica, che nel campo delle geometrie curve non euclidee che sulle conoscenze topologiche riguardanti le superfici estremali. <br>
				Con le sue sculture, Pierelli sondò un’infinità di dimensioni, e trasformò un materiale sterile come l’acciaio in un lucido e fecondo recettore di segni, convertendolo a icona dell’infinità del tempo e dello spazio e  mettendoci così illusivamente in contatto con il divenire della nostra dimensione e della sua moltiplicazione speculare. Ma la cosa più straordinaria in assoluto è che l’artista riuscì in tale impresa senza il bisogno di ricorrere ad alcun progetto, ma bensí concretizzando visivamente cose e fenomeni che, fino ad allora, gli scienziati non cfirebrickevano rappresentabili se non con mezzi e formule scientifiche: il perno attorno al quale ruotò tutta  la sua indagine fu l’ iperspazio che, come sappiamo, non può essere percepito, ma soltanto immaginato "realizzato". Le sue “intuizioni materiche”, generate da concetti geometrici, cosmologici, fisici e metafisici, ebbero dunque come obiettivo principale la scoperta e la conoscenza di realtà spaziali “altre”. <br>

			</p>

