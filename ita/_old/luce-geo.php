			<p class="text-content">
				Le sue sculture sono rivelazioni figurative di un principio estetico concepito nella realtà empirica, ma sono comunque oggetti nati con la volontà di “costruire” letteralmente una nuova dimensione, il tetraspazio. La <i>Pentacella</i> e la <i>Sedicicella</i> sono infatti figure geometriche appartenenti allo spazio quadridimensionale, ma costituite da tetraedri tridimensionali, rispettivamente cinque e sedici, e dunque percettivamente accessibili ai nostri occhi. La morfologia di tali superfici crea delle enigmatiche forme prismatiche rendendole portatrici attiranti di una luce che, oltre ad identificarsi con il fattore Spazio, introduce a sua volta anche il fattore Tempo. Se lo spazio è immoto, il tempo obbedisce comunque alle lentissime, ma pur sempre esistenti, variazioni della luce.
			</p>

