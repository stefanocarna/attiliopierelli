			<p class="text-header">
				luce e geometria (1974 - 1983)
			</p>

			<p class="text-content">
				In tutte le opere appartenenti ai periodi di ricerca precedenti, l’elemento <i>luce, fondamentale</i> per l’espressione artistica di Pierelli, e quindi il suo modo di colpire e riflettersi sulle superfici ondulate delle sculture, dipendevano soprattutto dal <i>caso</i>. Ma, a partire dal 1974, quest’ultimo ed imprevedibile fattore verrà sempre più ridotto,  fino ad essere definitivamente eliminato, a favore  dell'assoluto rigore geometrico.
			</p>

			<p class="text-content">
				Ed è infatti al periodo Luce e geometria che appartiene l’opera più rappresentativa di questo rivoluzionario cambiamento di prospettiva: l’Ipercubo. La scultura, un’inedita interpretazione dell'<i>ipercubo</i> geometrico quadridimensionale, costruita interamente in acciaio inox, è composta da un cubo interno ed uno esterno. La struttura speculare che si genera tra le facce del cubo esterno, assieme al gioco di specchi e riflessioni, rende il cubo interno sempre visibile da qualsiasi punto lo si osservi, come se fosse sospeso perennemente nello spazio. 
			</p>

