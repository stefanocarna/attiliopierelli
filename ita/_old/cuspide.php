			<p class="text-content">
				Stilisticamente parlando, invece, per rendere al meglio il fine ultimo dell’opera, Pierelli sembra essersi ispirato alla “formula” utilizzata dall’artista Getulio Alviani per donare dinamicità a tutte le sue opere, e che vede in una sorta di addizione logico-matematica (specularità + riflessione + fonte luminosa + angolazione visiva + movimento)<span class="text-tip"></span><a class="tip"title="M. Fagiolo dell’Arco, Rapporto 60: le arti oggi in Italia, op. cit., pp. 244-245."style="color: white;"><sup>2</sup></a> il raggiungimento di una corretta percezione della scultura. 
				Dall’ostile e rigoroso impiego di strumenti razionali, Pierelli sembra svincolarsi grazie all'utilizzo dell’immaginazione e della fantasia. 
			</p>

			<p class="text-content">
				«Quando colpisce un piano proiettato verso uno spazio infinito, Pierelli rappresenta la condizione umana. L’inquietudine che l’artista sente nei confronti della sua arte, che costituisce stimolo e ragione delle sue invenzioni, va intensificandosi proprio negli anni ’60 in cui ci fu il primo atto di rifiuto e di negazione nei confronti del fenomeno dell’Informale: rifiuto della creazione artistica per considerare invece tale attività un atto di ricerca, rifiuto delle tecniche tradizionali a favore di nuovi materiali, rifiuto dell’opera d’arte come unica ed irripetibile a favore di un atto sempre più diretto dell’osservatore nel senso di far intervenire, variare, programmare, costruire l’opera attraverso l’interazione con lo spettatore»<span class="text-tip"></span><a class="tip"title="C. Parisi, Extremalia: sculture di Attilio Pierelli, op. cit., p. 32."style="color: white;"><sup>3</sup></a>. 
			</p>

