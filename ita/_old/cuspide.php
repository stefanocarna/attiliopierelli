			<p class="text-content">
				La teoria di Thom, essendo nata come tentativo di spiegazione delle forme naturali, della loro permanenza, della loro genesi e dei conflitti che ne sono all’origine, se applicata alle opere di Pierelli, vedrebbe dunque in ognuna di esse il risultato di un dialogo/scontro agli antipodi tra arte e scienza. Tuttavia, se per la teoria delle catastrofi la specularità non fu una prerogativa necessaria, per l’arte di Pierelli essa fu essenziale, poiché grazie alla modulazione ottenuta con le varie tipologie di <i>Superficie a Cuspide</i> (o <i>Piastra INOX</i>), il punto di vista dell’osservatore A è sempre diverso dal punto di vista dell’osservatore B. Ciò avviene perché la forma della scultura-oggetto realizza una figura curva, ergo tutto ciò che si specchia in questa geometria non euclidea viene deformato, ed ogni spettatore assisterà così ad una sorta di versione di realtà “personalizzata”. Ed è proprio questo l'aspetto che determina la differenza tra le sculture di Pierelli e quelle tradizionali: quest’ultime non rispondono allo sguardo dell’osservatore con una loro vitale espressione fisica, che varia istantaneamente da un punto all’altro nello spazio che lo circonda; mentre l’essenza delle superfici pierelliane è che esse vivono e vengono vissute dall’ambiente. L’intento di Pierelli fu sempre quello di porre sotto analisi non tanto la scultura come oggetto, ma lo spazio intorno, quello in cui si trova colui che osserva; la sua preoccupazione primaria fu dunque quella di creare un movimento apparente, prodotto dallo spostamento dell’osservatore davanti all’opera oppure dalla diversa incidenza della luce sul metallo. Tale effetto venne creato affinché si producessero immagini deformate, movimenti vissuti, situazioni che stimolassero lo spettatore a “intervenire” con la propria immagine sull’opera, un orizzonte fatto di possibili avvenimenti. 
			</p>

			<p class="text-content">
				Tecnicamente parlando, <i>Piastra Inox</i> è costituita da una superficie quadrata d’acciaio inossidabile un metro per un metro, con spessore di due millimetri, che viene poi piegata con una macchina a pressione di qualche tonnellata partendo dal centro verso il bordo e facendo poi un'altra piega dalla parte opposta, circa quindici centimetri distante dall'altra, ma partendo sempre dal centro. 
			</p>

