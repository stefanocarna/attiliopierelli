			<p class="text-content">
				«Alcune volte, e per un insieme di ragioni molto complesse, capita che la sensibilità di un artista e di uno scienziato si incontrino e si sovrappongano perfettamente ignorando l’uno l’esistenza dell’altro. È questo il frutto di una intuizione comune che pur partendo da presupposti diversi per fini diversi, si nutre degli stessi germi culturali e arriva infine allo stesso risultato. È il caso ad esempio della scultura <i>Piastra Inox</i> realizzata da Pierelli nel 1965 e che coincide perfettamente nella forma con la superficie di equilibrio della catastrofe elementare nota col nome di "<i>Catastrofe a cuspide</i>". Ma a quell’epoca la teoria delle catastrofi di René Thom non era ancora nata. Nascerà poco dopo (1967-1968). E dopo ancora le innumerevoli applicazioni della teoria ai più svariati campi delle scienze umane, naturali e fisiche. Ed è interessante notare come il modello di catastrofe che più diffusamente ricorre nelle applicazioni, sia proprio quello a “cuspide” quello cioè creato da Pierelli.  Forse l’artista cercando effetti di riflessione particolari che riuscissero a decomporre l’immagine del soggetto è arrivato a questa "catastrofe" per vie sue, per sue intuizioni.  Le superfici speculari di Pierelli hanno per lo più lo scopo di deformare l'immagine riflessa in modo non regolare ponendo noi stessi dentro questo specchio, ritroviamo un'immagine di noi spezzata, contorta, incomprensibile, sempre nuova e piena di suggestioni psicologiche sul nostro senso di noi stessi. L'effetto è ottenuto con delle superfici speculari che hanno, in senso matematico, delle singolarità. Sono loro, le singolarità responsabili di questo sgretolamento e assorbimento dell'immagine. 
			</p>

			<p class="text-content">
				Così l'artista seguendo la propria strada, la propria ricerca, il proprio gusto estetico, è entrato nell'universo delle singolarità. Per altre strade e per altri scopi, in altro modo il matematico lì l’ha incontrato»<span class="text-tip"></span><a class="tip"title="F. Ghione, Dimensionalismo: advanced interdisciplinary art, op. cit., pp. 7-8."style="color: white;"><sup>1</sup></a>.
			</p>

			<p class="text-content">
				Con la sua teoria delle catastrofi René Thom cercò di applicare le più innovative ricerche topologiche all’interpretazione dei fenomeni naturali attraverso lo studio dei modelli matematici descriventi fenomeni discontinui, poiché causati dalla continua variazione dei parametri da cui dipendono. Secondo tale teoria, infatti, il mondo non sarebbe caotico (entropico), bensì governato da una serie di strutture ordinate e razionali, la cui regolare successione sarebbe poi oggetto d'indagine della morfologia. La scoperta di Renè Thom consistette nel fatto di dichiarare che i punti di instabilità di tali strutture non siano soggetti a configurazioni caotiche, ma a forme topologicamente stabili, ripetibili e soprattutto indipendenti dal fenomeno analizzato, che sia fisico, chimico, biologico, linguistico, storico, psicologico, o di altra natura. 
			</p>

			<p class="text-content">
				Le forme individuate e classificate da Thom come catastrofi, dove per catastrofe si intende un cambiamento improvviso di un processo strutturalmente stabile, furono sette e vennero chiamate <i>catastrofi elementari</i>: la piega, la cuspide, la coda di rondine, la farfalla, l’ombelico ellittico (piramide), l’ombelico iperbolico (portafoglio), l’ombelico parabolico (fungo). 
			</p>

