<p class="text-content">
Nella serie <i>Monumento Inox</i> le forme vengono ora complicate da movimenti avvolgenti e da superfici concave o convesse. L’acciaio viene lucidato con una cura quasi maniacale ed entra in competizione con lo spazio circostante che, oltre a venir modificato e ricreato dalla scultura, ne penetra e deforma a sua volta l’identità.  Come totemici varchi verso altre dimensioni, i <i>Monumenti Inox</i> innalzati verso il cielo rispecchiano lo spazio, inglobandolo e riflettendone poi un’immagine del tutto inedita. Così come i pittori tentarono nei secoli di andare al di là della superficie bidimensionale della tela, ecco che Pierelli, attraverso le sue strutture d’acciaio, tentava di dar luogo a una dissoluzione della forma nello spazio che riuscisse contemporaneamente a condurre la percezione umana ad un’integrazione dello spazio nella forma stessa. Ed è proprio questa la principale preoccupazione dell’artista, che comincia col perturbare e distruggere lo spazio abituale per abitarne uno trasposto, irreale, surreale.
</p>

