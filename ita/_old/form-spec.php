<p class="text-content">

	La luce che colpisce le opere è sempre una, poiché sono gli schermi che la raccolgono ad esser cento: molteplici schermi, molteplici sfaccettature. Attraverso queste sculture, Pierelli vuole dimostrare l’unità nella varietà della forma, una <i>coincidentia oppositorum</i> che ha la capacità di rinnovarsi ad ogni sussulto dello spettatore-attore. Il <i>mistero della luce</i><span class="text-tip"></span><a class="tip" 
		title="M. Fagiolo dell’Arco, Rapporto 60: le arti oggi in Italia, op. cit., p. 242."
		style="color: white;"><sup>2</sup></a> penetra in queste strutture, allineandosi in verticali o in orizzontali, rientrando o uscendo, rimbalzando o assorbendosi, scontrandosi o scivolando via.

</p>

