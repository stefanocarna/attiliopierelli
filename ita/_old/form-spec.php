<p class="text-content">
Sempre durante il periodo <i>Forma e specularità</i> Pierelli viene a conoscenza della teoria dell’iperspazio, scoperta che lo scultore marchigiano stesso non esitava a definire d’importanza almeno pari a quella della prospettiva per gli artisti del ‘400. Sculture come <i>Tortiglione</i> e <i>Monumento Inox</i> sembrano orientarsi proprio verso questa nuova direzione. Entrambe le opere sono rigorose strutture in acciaio all’interno delle quali la luce agisce non soltanto come elemento stilistico ma soprattutto come elemento formale e formante della loro continuamente nuova configurazione nello spazio.
</p>

