<p class="text-content">

Le opere di Pierelli dimostrano come la parabola della scienza sia soltanto un alibi per raggiungere la fantasia. Ad esse potremmo, infatti, attribuire il duale princila chiave della sua opera, fattore che permette alla materia di sprigionare un’energia luminosa che, a sua volta, può perfino distruggere la materia stessa. L’artista vuole introdurre, attraverso una forma “finita” come quella scultura, la possibilità di una creazione infinita di altre forme.
</p>


<div class="text-prev-img">
	<div class="prev-text">
		<p class="text-content lx-prev">
		Nata per stare all’aperto e donata dall’artista stesso all’Università degli Studi della Tuscia, <i>Onda</i> cerca di “ricostruire” la forma dell'omonimo elemento tipico della natura servendosi di una tecnica e di un materiale (l’acciaio inox) totalmente artificiali. Tramite quest’opera, Pierelli vuole insegnare all’osservatore una lezione importante: anche dietro le statiche forme geometriche bisogna saper vedere il tremolio organico della natura. Infatti, contrariamente a quanto si potrebbe pensare, la scultura, caratterizzata da una forma pura, monocolore ed essenziale, non stona in mezzo all’ambiente riccamente incontaminato dell’orto botanico, anzi lo risalta, catturando l’attenzione dell’osservatore attraverso un’unione inaspettata, che vede protagonisti le spontanee creazioni della natura con l’altrettanto genuina “creazione” artistica. 
		</p>
