	<div class="prev-text">
		<p class="text-content rx-prev">
		Il “<i>Monumento Inox</i>” donato all’Università di Tor Vergata è costituito da due lastre in acciaio inox contrapposte leggermente sfalsate. Ripercorrendole verticalmente, dal basso verso l’alto, ecco che si notano anche delle piegature (sette ciascuna per l’esattezza): le due laterali arrivano sino alla sommità, quella centrale - la più acuta - si ferma a due terzi, le quattro restanti si arrestano invece a un terzo. La parte inferiore di ogni lastra viene così modellata in un semicerchio irregolare, mentre la sommità rimane leggermente deformata verso l’esterno. La ripetizione illimitata e indistinta dell’immagine e della sua percezione riflessa trasforma l’opera in una sorta di modulo linguistico in fase di continua rielaborazione. 
		</p>
	</div>

