			<p class="text-content">
				La materializzazione di questa sequenza di “eventi” viene sapientemente descritta attraverso un processo di astrazione delle sue proprietà, che permette all’immagine di ridursi ad una wesenschau , ossia ad una percezione diretta della sua essenza.
			</p>

			<p class="text-content">
				Scientificamente parlando, l’eterea forma di questa scultura, può rimandare alla traduzione della logica matematica nell'istantaneità ideografica operata dal matematico Giuseppe Peano: "come l’ideogramma, anche T.E.S.T. è un’immagine segnaletica concreta che traduce simultaneamente il lessico simbolico semantico in pensiero visivo" . Altresì in campo artistico, l’opera potrebbe tranquillamente collegarsi alla filosofia del Costruttivismo russo degli anni Venti del Novecento e all’intuizione, rivelata da Naum Gabo, dell'unità di tutte le forme visibili e dell'esistenza di quelle estetiche solo in conformità a leggi fisiche e matematiche. Anche T.E.S.T. è un’intuizione, che trae però la sua origine dalle leggi della fisica, di cui ne è contemporaneamente l’esatta estensione artistica e visibile. 
			</p>
		
			
