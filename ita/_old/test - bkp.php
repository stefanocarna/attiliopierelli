			<p class="text-content">
				Subito dopo aver letto la monografia a cura di Joray, l’astrofisico Remo Ruffini chiese a Pierelli un appuntamento davanti alla Galleria Nazionale d’Arte Moderna di Roma. L’incontro, mediato dalla dottoressa Anna Imponente, si concluse con un lavoro su commissione, ossia la realizzazione di una piccola scultura da consegnare come premio al IV Marcel Grossmann Meeting  e raffigurante la materializzazione di un black hole . Teorizzati e scoperti dallo stesso Ruffini negli Stati Uniti all’inizio degli anni Settanta, i black holes (buchi neri) sono delle masse stellari che, sotto l'effetto della propria gravità, vengono inghiottiti a loro volta in un collasso gravitazionale. Sono oggetti senza luce, che attraggono e risucchiano il materiale da una stella in moto rotante, e che Pierelli è riuscito a riproporre in un’immagine quasi ipnotica. 
			</p>

			<p class="text-content">
				Una volta consegnate le esatte coordinate spaziali di Einstein, così da poterne ricavare una forma scientificamente coerente, Ruffini lasciò comunque a Pierelli la libertà di creare l’opera con tutti i mezzi artistici a sua disposizione. Una scommessa che lo scultore accettò e vinse clamorosamente, rappresentando con una forma plastica le precise traiettorie e reinterpretandole come oggetto estetico. 
				Per poter realizzare un’immagine del fenomeno totalmente attendibile, l’artista si orientò attraverso un disegno grafico già esperito scientificamente ed ottenuto al computer da Ruffini ed alcuni suoi collaboratori, dell’Università di Roma e di Princeton, nel 1974. Basandosi sulla geometria delle equazioni di Einstein, tale disegno rappresentò il moto di cinque particelle nello spazio tempo, un fenomeno calcolabile ma non sperimentabile ad occhio nudo e in tempo reale, appunto un black hole. Pierelli dovette dunque procedere nell’esecuzione di una maquette che rispettasse, negli avvolgimenti e nelle torsioni, proporzioni numeriche calcolate con esattezza. Il risultato fu un oggetto dinamico, privo di alcun verso privilegiato di lettura o simmetria e senza alcun piedistallo d’appoggio che possa ricondurlo a una centralità di visione prospettica, poiché ogni punto di vista rappresenta una realizzazione compiuta e differente. 
			</p>

